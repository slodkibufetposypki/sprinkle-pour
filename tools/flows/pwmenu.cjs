const { chromium } = require('playwright');
(async () => {
  const base = process.argv[2], out = process.argv[3];
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage(); const errs = [];
  p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g/.test(m.text())) errs.push(m.text()); });
  p.on('response', (r) => { if (r.status() >= 400) errs.push(r.status() + ' ' + r.url()); });
  await p.goto(base + (process.argv[4] || 'local.html')); await p.waitForTimeout(2500);
  console.log('film:', await p.evaluate(() => { const v = document.querySelector('video') || null; return null; }));
  await p.screenshot({ path: out + '/m-room.png' });
  await p.evaluate(() => { const s = __grainLine.save; [5, 4, 4, 3, 3, 3, 2, 2, 2, 2].forEach((n, i) => { s.levels[__grainLine.levelId(i)] = { stars: n, best: 900, plays: 1 }; }); });
  await p.tap('#enterBtn'); await p.waitForTimeout(600); await p.screenshot({ path: out + '/m-move.png' });
  await p.waitForTimeout(1600);
  console.log('screen', await p.evaluate(() => __grainLine.screen), '| night sound', await p.evaluate(() => typeof Night));
  const info = await p.evaluate(() => [...document.querySelectorAll('.bpage')].map((e) => e.dataset.board + ':' + e.querySelectorAll('.lcard').length + (e.classList.contains('locked') ? ' locked' : '')));
  console.log('pages', info, '| showing', await p.evaluate(() => Math.round(document.getElementById('boardRail').scrollLeft / document.getElementById('boardRail').clientWidth)));
  await p.screenshot({ path: out + '/m-menu.png' });
  await p.evaluate(() => { const r = document.getElementById('boardRail'); r.scrollTo({ left: r.scrollLeft - r.clientWidth, behavior: 'instant' }); });
  await p.waitForTimeout(500); await p.screenshot({ path: out + '/m-menu-prev.png' });
  console.log('after swipe, dots on', await p.evaluate(() => [...document.querySelectorAll('#boardDots i')].findIndex((d) => d.classList.contains('on'))));
  await p.evaluate(() => { const r = document.getElementById('boardRail'); r.scrollTo({ left: r.scrollLeft + r.clientWidth * 2, behavior: 'instant' }); });
  await p.waitForTimeout(500); await p.screenshot({ path: out + '/m-menu-iron.png' });
  await p.evaluate(() => { const r = document.getElementById('boardRail'); r.scrollTo({ left: r.clientWidth, behavior: 'instant' }); });
  await p.waitForTimeout(500);
  await p.evaluate(() => document.querySelector('.bpage[data-board="walnut"] .lcard.next').click());
  await p.waitForTimeout(150); await p.screenshot({ path: out + '/m-start-a.png' });
  await p.waitForTimeout(900); await p.screenshot({ path: out + '/m-start-b.png' });
  console.log('playing', await p.evaluate(() => [__grainLine.screen, __grainLine.sim && __grainLine.sim.level && __grainLine.sim.level.id]));
  console.log('errors', errs.length ? errs : 'none');
  await b.close();
})();
